import { chromium } from "playwright";
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: process.env.BENCH_BROWSER });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.setDefaultTimeout(120000);
await page.goto("http://localhost:3000/play");
await page.waitForResponse((r) => new URL(r.url()).pathname === "/api/title").catch(()=>{});
const life = page.waitForResponse((r) => new URL(r.url()).pathname === "/api/newlife", { timeout: 300000 });
await page.locator("#new-life").click();
await page.locator("#new-world").click();
const r = await life;
console.log("seed", new URL(r.url()).searchParams.get("seed"));
await page.locator("#opening-box:not([hidden])").waitFor({ timeout: 120000 });
await page.keyboard.press("Escape");
await page.getByRole("button", { name: "Skip opening", exact: true }).click();
await page.waitForFunction(() => document.getElementById("card-name").textContent.trim());
console.log("player", await page.locator("#card-name").innerText(), "|", await page.locator("#card-place").innerText());
const n = await page.locator("#people .talkable").count();
console.log("talkable", n);
for (let i = 0; i < Math.min(n, 2); i++) {
  const known = page.waitForResponse((r) => new URL(r.url()).pathname === "/api/known");
  await page.locator("#people .talkable").nth(i).focus();
  await page.keyboard.press("Enter");
  const json = await (await known).json();
  console.log(JSON.stringify({ ...json, presentation: undefined, figureUrl: undefined }).slice(0, 900));
  await page.locator("#person:not([hidden])").waitFor();
  await page.waitForTimeout(800);
  console.log("TEXT:", (await page.locator("#person").innerText()).replace(/\n+/g, " | "));
  await page.screenshot({ path: `${out}-${i}.png` });
  await page.keyboard.press("Escape");
  await page.locator("#person").waitFor({ state: "hidden" });
}
await browser.close();
