import { chromium } from "playwright";
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.setDefaultTimeout(60000);
const ready = page.waitForResponse((r) => r.url().endsWith("/api/title"));
await page.goto("http://localhost:3000/play");
await ready;
const response = page.waitForResponse((r) => new URL(r.url()).pathname === "/api/newlife", { timeout: 400000 });
await page.locator("#new-life").click();
await page.locator("#new-advanced").click();
await page.locator("#new-world").click();
const r = await response;
console.log("Seed:", new URL(r.url()).searchParams.get("seed"));
await page.locator("#opening-box:not([hidden])").waitFor({ timeout: 200000 });
await page.keyboard.press("Escape");
await page.getByRole("button", { name: "Skip opening", exact: true }).click();
await page.waitForFunction(() => document.getElementById("card-name").textContent.trim());
console.log("Player:", await page.locator("#card-name").innerText(), "Place:", await page.locator("#card-place").innerText());
await page.locator('[data-tab="travel"]').first().evaluate((e) => e.click());
await page.locator(".travel-destinations").waitFor();
await page.screenshot({ path: out });
console.log("travel-from count", await page.locator(".travel-from").count());
await browser.close();
