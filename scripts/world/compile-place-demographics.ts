interface CompiledDemographics {
  columns: string[];
  sources: unknown[];
  rows: (string | number | null)[][];
  annualSource: unknown;
  annualRows: (string | number)[][];
  territoryRows: unknown[];
  decennialRows: (string | number | null)[][];
  decennialSources: unknown[];
  stateKeys: Record<string, string>;
}
function render(output: CompiledDemographics): string {
  const packed = (rows: (string | number | null)[][]) =>
    JSON.stringify(
      rows.map((row) => row.map((value) => value ?? "").join(",")).join(";"),
    );
  return `/** GENERATED by scripts/world/compile-place-demographics.ts. Normalized source rows and receipts: data/research/census/place-demographics-2024.json. */\nexport const PLACE_DEMOGRAPHIC_COLUMNS = ${JSON.stringify(output.columns)} as const;\nexport const PLACE_DEMOGRAPHIC_SOURCES = ${JSON.stringify(output.sources)} as const;\n/** GEOID,vintage,then columns; empty cells are suppressed or unavailable, never zero. */\nexport const PLACE_DEMOGRAPHIC_ROWS: string = ${packed(output.rows)};\nexport const ANNUAL_POPULATION_SOURCE = ${JSON.stringify(output.annualSource)} as const;\nexport const ANNUAL_POPULATION_ROWS: string = ${packed(output.annualRows)};\nexport const TERRITORY_POPULATION_ROWS = ${JSON.stringify(output.territoryRows)} as const;\nexport const DECENNIAL_POPULATION_ROWS: string = ${packed(output.decennialRows)};\nexport const DECENNIAL_POPULATION_SOURCES = ${JSON.stringify(output.decennialSources)} as const;\nexport const STATE_POPULATION_KEYS: Readonly<Record<string,string>> = ${JSON.stringify(output.stateKeys)};\n`;
}
