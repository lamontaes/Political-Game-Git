/** Compile locked Census bulk selections into the browser-safe population layer.
 * Run: node --import tsx scripts/world/compile-place-demographics.ts <selection-dir>
 * The selections retain original Census headers and are verified against receipts.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
