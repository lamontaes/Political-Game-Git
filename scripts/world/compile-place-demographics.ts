for (const row of decennialRows) {
  if (row[1] !== null) continue;
  const profile = islandProfiles.find(
    (item) =>
      item.summaryLevel === (String(row[0]).length === 2 ? "040" : "050") &&
      item.geoId.endsWith(`US${row[0]}`),
  );
  if (profile) row[1] = profile.population2020;
}
