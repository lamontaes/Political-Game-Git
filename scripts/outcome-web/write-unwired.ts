/**
 * Writes src/core2/data/outcome-web/unwired.json: every researched link whose
 * effect does not yet reach an engine's own records, with the exact reason
 * (from the effect matrix) and the open stopgap that carries it. A link a
 * family's own stopgap row already names keeps that row; the rest share one
 * row per outcome measure; a shared row no link cites any more is kept as
 * resolved. src/core2/outcome-web-unwired.test.ts fails when
 * this file and the matrix disagree.
 *
 *   node --import tsx scripts/outcome-web/write-unwired.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { matrix } from "./effect-matrix";

const UNWIRED = "src/core2/data/outcome-web/unwired.json";
const STOPGAPS = "src/core2/data/stopgaps.json";
/** The resolution of a shared row whose every link now reaches an engine's records. */
const REACHED =
  "Resolved: every link this row named now reaches an engine's own records or is carried by one (scripts/outcome-web/effect-matrix.ts grades it as reaching), so it is off the unwired list.";
/** The resolution of a shared row whose every link its research finds about zero. */
const ABOUT_ZERO =
  "Resolved: the research finds every link this row named about zero, so there is no effect for an engine to read (scripts/outcome-web/effect-matrix.ts grades it not applicable), and it is off the unwired list.";

/**
 * What a shared row's links fake. A link the web runs moves its outcome in the
 * monthly ledger that no engine reads; a link the web never runs (its cause is
 * not recorded, its research gives no size, or its outcome is not kept) moves
 * nothing at all, and its own reason says why.
 */
function fakes(links: readonly UnwiredRow[], outcome: string): string {
  const notRun = (l: UnwiredRow) =>
    l.reason.startsWith("the web does not run it") ||
    l.reason.startsWith("no measure");
  const ledger = links.filter((l) => !notRun(l));
  const parts: string[] = [];
  if (ledger.length)
    parts.push(
      `${ledger.map((l) => l.link).join(", ")} ${ledger.length === 1 ? "moves" : "move"} ${outcome} only in the outcome web's monthly ledger`,
    );
  for (const l of links.filter(notRun))
    parts.push(
      `${l.link} is not run by the outcome web, so it moves nothing (${l.reason.replace(/^the web does not run it: /, "")})`,
    );
  return `${parts.join("; ")}; no person, household or organization record changes.`;
}

export interface UnwiredRow {
  readonly link: string;
  readonly outcome: string;
  readonly reason: string;
  readonly stopgapId: string;
}

const slug = (measure: string) => measure.replace(/[^a-z0-9]+/g, "-");
export const unreadId = (measure: string) => `SG-WEB-unread-${slug(measure)}`;

/** The rows the matrix gives today, in link order. */
export function unwiredRows(): UnwiredRow[] {
  return matrix()
    .links.filter(
      (row) =>
        row.points.reaches!.status !== "pass" &&
        row.points.reaches!.status !== "n/a",
    )
    .map((row) => ({
      link: row.key,
      outcome: row.to,
      reason: row.points.reaches!.why!,
      stopgapId: row.stopgap ?? unreadId(row.to),
    }));
}

if (process.argv[1]?.endsWith("write-unwired.ts")) {
  const rows = unwiredRows();
  const text = `${JSON.stringify(
    {
      about:
        "Every researched outcome-web link whose effect does not yet reach an engine's own records, with the reason and the open stopgap that carries it. Generated by scripts/outcome-web/write-unwired.ts from the effect matrix.",
      links: rows,
    },
    null,
    2,
  )}\n`;
  writeFileSync(UNWIRED, text);
  // One registry row per new shared id, pointing at its first marker line.
  const lines = text.split("\n");
  const registry = JSON.parse(readFileSync(STOPGAPS, "utf8")) as {
    id: string;
    file?: string;
    line?: number;
    status?: string;
  }[];
  const byId = new Map<string, UnwiredRow[]>();
  for (const row of rows)
    if (row.stopgapId.startsWith("SG-WEB-unread-"))
      byId.set(row.stopgapId, [...(byId.get(row.stopgapId) ?? []), row]);
  // A shared row no unwired link cites any more stays in the registry as
  // resolved, its history kept. Its resolution says what became of its links:
  // those still unwired wait on the stopgap that now carries them (it is
  // superseded), and the rest reach an engine's records. A row resolved with
  // the old reaching text is read again, so the history stays true.
  const waitingOn = new Map(rows.map((row) => [row.link, row.stopgapId]));
  const graded = matrix().links;
  const linkKeys = new Set(graded.map((row) => row.key));
  const aboutZero = new Set(
    graded
      .filter((row) => row.points.reaches!.status === "n/a")
      .map((row) => row.key),
  );
  const resolution = (whatItFakes = "") => {
    // Each clause of the text opens with the links it names ("a, b move ...;
    // c is not run ..."); only known link keys are kept.
    const named = whatItFakes
      .split("; ")
      .flatMap((part) =>
        (/^([a-z0-9-]+(?:, [a-z0-9-]+)*) /.exec(part)?.[1] ?? "").split(", "),
      )
      .filter(Boolean);
    const by = [
      ...new Set(
        named.flatMap((key) => {
          const id = waitingOn.get(key);
          return id ? [id] : [];
        }),
      ),
    ].sort();
    if (by.length)
      return `Superseded by ${by.join(", ")}: the links this row named that still do not reach an engine's records now wait on ${by.length === 1 ? "that stopgap" : "those stopgaps"} instead (src/core2/data/outcome-web/unwired.json); any others reach an engine's records (scripts/outcome-web/effect-matrix.ts). It is off the unwired list.`;
    // The clause openers include plain words ("no person ..."): keep link keys.
    const links = named.filter((key) => linkKeys.has(key));
    return links.length && links.every((key) => aboutZero.has(key))
      ? ABOUT_ZERO
      : REACHED;
  };
  const kept = registry.map((row) =>
    row.id.startsWith("SG-WEB-unread-") &&
    !byId.has(row.id) &&
    (row.status !== "resolved" ||
      (row as { replacement?: string }).replacement === REACHED ||
      (row as { replacement?: string }).replacement === ABOUT_ZERO)
      ? {
          ...row,
          status: "resolved",
          replacement: resolution(
            (row as { whatItFakes?: string }).whatItFakes,
          ),
        }
      : row,
  );
  for (const [id, links] of byId) {
    const line = lines.findIndex((l) => l.includes(`"stopgapId": "${id}"`)) + 1;
    const outcome = links[0]!.outcome;
    const noMeasure = links[0]!.reason.startsWith("no measure");
    const entry = {
      id,
      kind: noMeasure ? "missing-record" : "missing-mechanic",
      file: UNWIRED,
      line,
      whatItFakes: fakes(links, outcome),
      why: links[0]!.reason,
      addedBy: "EFFECT-WEB-WIRING",
      addedAt: "2026-10-20",
      replacement: noMeasure
        ? `An engine that records ${outcome} for each place from its own people or organizations, read by the web as an engine measure, and whose own rates read webReach for these links.`
        : `The engine that owns ${outcome} multiplies its own person, household or organization rate by webReach(api, placeId, "${outcome}", subject), as counted births do, so these links change its records.`,
      status: "open",
    };
    const at = kept.findIndex((row) => row.id === id);
    if (at >= 0) kept[at] = entry;
    else kept.push(entry);
  }
  writeFileSync(STOPGAPS, `${JSON.stringify(kept, null, 2)}\n`);
  console.log(`${rows.length} unwired links, ${byId.size} shared stopgap rows`);
}
