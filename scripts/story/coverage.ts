/**
 * The coverage map (the CTO, Nov 24, 7140057819 on #9750: "A coverage map
 * drives what gets made"): for each policy in the bill catalog, by kind of
 * text, how many elements name it and how many bank lines are about it.
 * Writes docs/story/coverage.md, so a writer picks the thinnest cells first.
 *
 * An element names its policies in `issues` (catalog ids, or ["none"]); its
 * kinds of text are its `fits`. A line is about a policy when it names it in
 * its own `issues`, requires it as a `policy:<id>` fact (the planner's
 * policy facts, src/english/outline-planner.ts), or cites an element that
 * names it; its kind of text is its bank's.
 *
 * Run: node --import tsx scripts/story/coverage.ts
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { format } from "prettier";
import { catalogPolicies } from "./policies";

// Run from the repository's root.
const ROOT = process.cwd();
const ELEMENTS = path.join(ROOT, "docs/story/elements");
const PARTS = path.join(ROOT, "data/english/parts");
const OUT = path.join(ROOT, "docs/story/coverage.md");

/** The kinds of text, as the elements' `fits` name them, plus the scenes. */
const KINDS = [
  "speeches",
  "news",
  "journal",
  "home",
  "office",
  "campaign",
  "work-community",
  "loading",
  "scenes",
] as const;

/** A bank's kind of text; a bank not listed counts under none. */
const BANK_KIND: Readonly<Record<string, string>> = {
  "outline-call": "speeches",
  "outline-theme": "speeches",
  "outline-local": "speeches",
  "opening-speech": "speeches",
  "speech-stages": "speeches",
  outline: "speeches",
  "outline-news": "news",
  news: "news",
  newscast: "news",
  headlines: "news",
  journal: "journal",
  "outline-diary": "journal",
  "outline-journal": "journal",
  "person-history": "journal",
  conversation: "home",
  "outline-talk": "home",
  "bring-it-up": "home",
  meeting: "office",
  "bill-paper": "office",
  notice: "office",
  "campaign-standing": "campaign",
  "outline-loading": "loading",
  "scene-talk": "scenes",
};

const policies = catalogPolicies();
const ids = new Set(policies.map((policy) => policy.id));
const count = new Map<string, Map<string, { e: number; l: number }>>();
const cell = (id: string, kind: string) => {
  const row = count.get(id) ?? new Map<string, { e: number; l: number }>();
  count.set(id, row);
  const at = row.get(kind) ?? { e: 0, l: 0 };
  row.set(kind, at);
  return at;
};

// Elements: their issues, by the kinds of text they fit.
const elementIssues = new Map<string, readonly string[]>();
let elements = 0;
let tagged = 0;
let issueFree = 0;
if (existsSync(ELEMENTS))
  for (const kind of readdirSync(ELEMENTS, { withFileTypes: true }))
    if (kind.isDirectory())
      for (const file of readdirSync(path.join(ELEMENTS, kind.name)))
        if (file.endsWith(".json")) {
          const element = JSON.parse(
            readFileSync(path.join(ELEMENTS, kind.name, file), "utf8"),
          ) as { id?: string; issues?: string[]; fits?: string[] };
          const id = element.id ?? file.replace(/\.json$/, "");
          elements += 1;
          if (!Array.isArray(element.issues)) continue;
          tagged += 1;
          if (element.issues.includes("none")) {
            issueFree += 1;
            continue;
          }
          elementIssues.set(id, element.issues);
          for (const policy of element.issues)
            if (ids.has(policy))
              for (const fit of element.fits ?? []) cell(policy, fit).e += 1;
        }

// Lines: their own issues, the policies they require, and their elements'.
let lines = 0;
let aboutPolicy = 0;
for (const file of readdirSync(PARTS).filter((name) =>
  name.endsWith(".json"),
)) {
  const kind = BANK_KIND[file.replace(/\.json$/, "")];
  const bank = JSON.parse(readFileSync(path.join(PARTS, file), "utf8")) as {
    parts?: {
      issues?: string[];
      elements?: string[];
      uses?: { requiresFacts?: string[] }[];
    }[];
  };
  for (const part of bank.parts ?? []) {
    lines += 1;
    const about = new Set<string>([
      ...(part.issues ?? []),
      ...(part.uses ?? []).flatMap((use) =>
        (use.requiresFacts ?? [])
          .filter((fact) => fact.startsWith("policy:"))
          .map((fact) => fact.slice("policy:".length)),
      ),
      ...(part.elements ?? []).flatMap((id) => elementIssues.get(id) ?? []),
    ]);
    const known = [...about].filter((id) => ids.has(id));
    if (known.length) aboutPolicy += 1;
    if (kind) for (const policy of known) cell(policy, kind).l += 1;
  }
}

const said = (at: { e: number; l: number } | undefined) =>
  at && (at.e || at.l) ? `${at.e}/${at.l}` : "·";
const empty = policies.filter((policy) => !count.has(policy.id)).length;
const out: string[] = [
  "# Coverage: the game's policies by kind of text",
  "",
  "Generated by `node --import tsx scripts/story/coverage.ts`; do not edit by hand. Each cell is elements/lines about that policy for that kind of text (· is none). An element names its policies in `issues`; a line is about a policy through its own `issues`, a `policy:<id>` fact it requires, or an element it cites. Pick the thinnest cells first, issue first, in both directions (the CTO, Nov 24, 7140057819 on #9750).",
  "",
  `- **Policies:** ${policies.length} in the bill catalog; ${empty} with no element and no line.`,
  `- **Elements:** ${elements}, of which ${tagged} name their issues (${issueFree} issue-free).`,
  `- **Lines:** ${lines} in the banks, of which ${aboutPolicy} are about a policy.`,
  "",
];
let subject = "";
for (const policy of policies) {
  if (policy.subject !== subject) {
    subject = policy.subject;
    out.push(
      "",
      `## ${subject}`,
      "",
      `| Policy | Levels | ${KINDS.join(" | ")} |`,
      `| --- | --- | ${KINDS.map(() => "---").join(" | ")} |`,
    );
  }
  const row = count.get(policy.id);
  out.push(
    `| ${policy.name} (\`${policy.id}\`) | ${policy.levels.join(", ")} | ${KINDS.map((kind) => said(row?.get(kind))).join(" | ")} |`,
  );
}
// Formatted as the repository formats Markdown, so the generated file passes the format check.
writeFileSync(OUT, await format(`${out.join("\n")}\n`, { parser: "markdown" }));
console.log(
  `${policies.length} policies, ${empty} empty; ${tagged} of ${elements} elements tagged; ${aboutPolicy} of ${lines} lines about a policy. Wrote ${path.relative(ROOT, OUT)}.`,
);
