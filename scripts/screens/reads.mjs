/* global console */
/**
 * Every table a screen (src/bench) opens in an engine's module state, by engine: file and line, table, and the
 * operation after it (a row by id, every row, or a row query by index). Run it to refresh
 * docs/coordination/refactor/screens-reads-2026-11-27.md (Screens, item 7); each engine's session reads its own
 * block to build the door the screens switch to. A reader of this list asks the engine's door, never the table.
 *
 *   node scripts/screens/reads.mjs > docs/coordination/refactor/screens-reads-2026-11-27.md
 */
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import ts from "typescript";
const files = execFileSync("git", ["ls-files", "src/bench"], {
  encoding: "utf8",
})
  .split("\n")
  .filter((f) => /\.(ts|mjs)$/.test(f) && !/\.(test|browser)\./.test(f));
const rows = [];
for (const file of files) {
  const text = readFileSync(file, "utf8");
  if (!text.includes(".table(")) continue;
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.ES2022, true);
  const vars = new Map();
  sf.forEachChild(function walk(n) {
    if (
      ts.isVariableDeclaration(n) &&
      n.initializer &&
      ts.isIdentifier(n.name)
    ) {
      const m = /moduleState\(\s*([A-Za-z_"'.\-0-9]+)\s*\)/.exec(
        n.initializer.getText(),
      );
      if (m) vars.set(n.name.text, m[1].replace(/["']/g, ""));
    }
    n.forEachChild(walk);
  });
  sf.forEachChild(function walk(n) {
    if (
      ts.isCallExpression(n) &&
      ts.isPropertyAccessExpression(n.expression) &&
      n.expression.name.text === "table" &&
      n.arguments[0] &&
      ts.isStringLiteralLike(n.arguments[0])
    ) {
      const recv = n.expression.expression;
      let engine = "?";
      const m = /moduleState\(\s*([A-Za-z_"'.\-0-9]+)\s*\)/.exec(
        recv.getText(),
      );
      if (m) engine = m[1].replace(/["']/g, "");
      else if (ts.isIdentifier(recv) && vars.has(recv.text))
        engine = vars.get(recv.text);
      // the operation that follows: .get / .rows / .query("index")
      const parent = n.parent;
      let op = "?";
      if (
        ts.isPropertyAccessExpression(parent) &&
        ts.isCallExpression(parent.parent)
      ) {
        op = parent.name.text;
        if (op === "query" && parent.parent.arguments[0])
          op += `(${parent.parent.arguments[0].getText().replace(/\s+/g, " ")})`;
      }
      rows.push({
        file,
        line: sf.getLineAndCharacterOfPosition(n.getStart()).line + 1,
        engine,
        table: n.arguments[0].text,
        op,
      });
    }
    n.forEachChild(walk);
  });
}
const ENGINES = [
  [/^(OFFICES|core2-offices)/, "offices"],
  [/^(ELECTIONS|core2-elections)/, "elections"],
  [/^(CAMPAIGNS|core2-campaigns)/, "campaigns"],
  [/^(PARTIES|core2-parties)/, "parties"],
  [/^(VOTING|core2-voting)/, "voting"],
  [/^(LAWS|core2-laws)/, "laws"],
  [/^(LEGISLATURE|core2-legislature)/, "legislature"],
  [/^(BUDGETS|core2-budgets)/, "budgets"],
  [/^credit/, "credit"],
  [/^(MACRO|REGIONAL)/, "macro"],
  [/^place-prices/, "place-prices"],
  [/^JOBS/, "jobs"],
  [/^BUSINESS/, "business"],
  [/^HOUSING/, "housing"],
  [/^COVERAGE/, "coverage"],
  [/^PEOPLE/, "people"],
  [/^(PRESS|news)/, "press and news"],
];
for (const r of rows)
  r.engine =
    ENGINES.find(([pattern]) => pattern.test(r.engine))?.[1] ?? r.engine;
console.log(`# What the screens read from each engine's tables (Nov 27, 2026)

Generated by scripts/screens/reads.mjs from src/bench (tests left out; dev panels and the milestone checks included). Each line is a table, the operation after it, and where it is opened. The count in each heading is the number of opens. Each engine's session builds the read door for its block (CTO, 1:57 a.m., Nov 27: Screens builds no door in another engine), and Screens switches the screens' reads when the door lands.`);
const by = new Map();
for (const r of rows) {
  const k = r.engine;
  (by.get(k) ?? by.set(k, []).get(k)).push(r);
}
for (const [engine, list] of [...by].sort(
  (a, b) => b[1].length - a[1].length,
)) {
  console.log(`\n## ${engine} (${list.length})`);
  const tables = new Map();
  for (const r of list) {
    const k = `${r.table} ${r.op}`;
    (tables.get(k) ?? tables.set(k, []).get(k)).push(
      `${r.file.replace("src/bench/", "")}:${r.line}`,
    );
  }
  for (const [k, where] of [...tables].sort())
    console.log(
      `- ${k}: ${where.slice(0, 6).join(", ")}${where.length > 6 ? ` (+${where.length - 6})` : ""}`,
    );
}
console.log("\ntotal", rows.length);
