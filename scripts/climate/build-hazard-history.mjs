/**
 * Each county's recorded hazard history by season (Nation, Nov 9, 2026): how
 * many FEMA declarations began in the county, by hazard and season, from
 * 2000-01-01 through the record's end. A statewide declaration counts in every
 * county of its state, as the disasters module reads it. Heat and drought are
 * not here: FEMA declares almost none (one drought), so their history is the
 * NOAA storm episodes' work (stopgap SG-NATION-hazard-heat-drought-history).
 * Run: node scripts/climate/build-hazard-history.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";

const declarations = JSON.parse(
  readFileSync("src/core2/data/disasters/declarations.json", "utf8"),
);
const lookup = JSON.parse(
  readFileSync("src/core2/data/places/place-lookup.json", "utf8"),
);
const FIRST = "2000-01-01";
const LAST = "2026-10-09";
const HAZARD_OF = {
  Flood: "flood",
  "Mud/Landslide": "flood",
  "Dam/Levee Break": "flood",
  "Coastal Storm": "flood",
  Hurricane: "storm",
  "Tropical Storm": "storm",
  "Tropical Depression": "storm",
  Typhoon: "storm",
  "Severe Storm": "storm",
  Tornado: "storm",
  "Straight-Line Winds": "storm",
  Fire: "wildfire",
};
const SEASON_OF_MONTH = [0, 0, 1, 1, 1, 2, 2, 2, 3, 3, 3, 0]; // winter, spring, summer, fall
const HAZARDS = ["flood", "storm", "wildfire"];
const years =
  (Date.parse(`${LAST}T00:00:00Z`) - Date.parse(`${FIRST}T00:00:00Z`)) /
  (365.25 * 86_400_000);

const counties = lookup.counties.rows.map((row) => row[0]);
const counts = new Map(
  counties.map((geoid) => [geoid, HAZARDS.map(() => [0, 0, 0, 0])]),
);
// A disaster counts once in a county, as the disasters module reads it, even
// when it is listed for the county and for its whole state.
const counted = new Set();
const add = (geoid, row) => {
  if (counted.has(`${geoid}|${row[4]}`)) return;
  counted.add(`${geoid}|${row[4]}`);
  const hazard = HAZARD_OF[declarations.types[row[2]]];
  if (!hazard || row[0] < FIRST || row[0] > LAST) return;
  const cell = counts.get(geoid);
  if (!cell) return;
  cell[HAZARDS.indexOf(hazard)][
    SEASON_OF_MONTH[Number(row[0].slice(5, 7)) - 1]
  ] += 1;
};
for (const [key, rows] of Object.entries(declarations.byCounty)) {
  for (const row of rows) {
    if (key.endsWith("000")) {
      for (const geoid of counties)
        if (geoid.slice(0, 2) === key.slice(0, 2)) add(geoid, row);
    } else add(key, row);
  }
}
const byCounty = {};
for (const [geoid, cell] of counts)
  if (cell.some((h) => h.some((n) => n > 0))) byCounty[geoid] = cell;
const head = {
  about:
    "Declarations that began in each county, by hazard (flood, storm, wildfire) and season (winter, spring, summer, fall), 2000-01-01 to 2026-10-09. Generated by scripts/climate/build-hazard-history.mjs from the FEMA declarations (src/core2/data/disasters/declarations.json). A county missing here had none.",
  source: declarations.source,
  hazards: HAZARDS,
  hazardOfIncidentType: HAZARD_OF,
  recordEnd: LAST,
  years: Math.round(years * 1000) / 1000,
};
// One line a county, so the file stays small and a diff reads by county.
const lines = Object.entries(byCounty).map(
  ([geoid, cell]) => `    ${JSON.stringify(geoid)}: ${JSON.stringify(cell)}`,
);
const top = JSON.stringify(head, null, 2).replace(/\n}$/, "");
writeFileSync(
  "src/core2/data/climate/hazard-history.json",
  `${top},\n  "byCounty": {\n${lines.join(",\n")}\n  }\n}\n`,
);
process.stdout.write(
  `${Object.keys(byCounty).length} counties with a history over ${years.toFixed(2)} years\n`,
);
