import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import console from "node:console";
import process from "node:process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const REPOSITORY_ROOT = resolve(dirname(SCRIPT_PATH), "../..");
const EFFECTS_DIRECTORY = "src/simulation/traits/effects";
const INDEX_PATH = `${EFFECTS_DIRECTORY}/index.ts`;
const NOT_A_READER = /(?:^index\.ts$|\.test\.ts$|^trait-proof-support\.ts$)/;
const READER_EXPORT =
  /^export const ([a-zA-Z0-9]+Effects)\s*:\s*(?:readonly TraitEffectDeclaration\[\]|TraitPack\["effects"\])/m;

/**
 * Every leaf module that exports effect rows (`readonly TraitEffectDeclaration[]`
 * or `TraitPack["effects"]`) named <trait>Effects. Other files in the folder (packs, support code) are not rows.
 */
export function discoverTraitEffectReaders(root = REPOSITORY_ROOT) {
  const directory = resolve(root, EFFECTS_DIRECTORY);
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".ts"))
    .map((entry) => entry.name)
    .filter((name) => !NOT_A_READER.test(name))
    .sort((left, right) => left.localeCompare(right))
    .flatMap((name) => {
      const source = readFileSync(resolve(directory, name), "utf8");
      const binding = READER_EXPORT.exec(source)?.[1];
      return binding ? [{ module: name.slice(0, -3), binding }] : [];
    });
}

export function renderTraitEffectsIndex(readers) {
  const rows = [...readers];
  if (new Set(rows.map((row) => row.binding)).size !== rows.length)
    throw new Error("Trait effect bindings must be unique.");
  const imports = rows.map(
    ({ binding, module }) => `import { ${binding} } from "./${module}";`,
  );
  const spreads = rows.map(({ binding }) => `...${binding}`);
  const inline = `  return [${spreads.join(", ")}];`;
  return [
    "// Generated by scripts/trait-effects/generate-manifest.mjs. Do not edit by hand.",
    'import type { TraitEffectDeclaration } from "../../trait-packs";',
    ...imports,
    "",
    "/**",
    " * The catalog's effect readers, one trait per leaf module. Adding a trait",
    " * means adding its file; run npm run generate:trait-effects to register it.",
    " */",
    "export function personalityTraitEffects(): readonly TraitEffectDeclaration[] {",
    ...(inline.length <= 80
      ? [inline]
      : ["  return [", ...spreads.map((spread) => `    ${spread},`), "  ];"]),
    "}",
    "",
  ].join("\n");
}

export function checkTraitEffectsIndex(root = REPOSITORY_ROOT) {
  const path = resolve(root, INDEX_PATH);
  const expected = renderTraitEffectsIndex(discoverTraitEffectReaders(root));
  const actual = existsSync(path) ? readFileSync(path, "utf8") : null;
  return { matches: actual === expected, actual, expected, path };
}

export function writeTraitEffectsIndex(root = REPOSITORY_ROOT) {
  const result = checkTraitEffectsIndex(root);
  if (!result.matches) writeFileSync(result.path, result.expected);
  return result;
}

if (process.argv[1] && resolve(process.argv[1]) === SCRIPT_PATH) {
  const checkOnly = process.argv.includes("--check");
  const result = checkTraitEffectsIndex();
  if (checkOnly && !result.matches) {
    console.error(
      "Trait effects index is out of date. Run npm run generate:trait-effects.",
    );
    process.exitCode = 1;
  } else if (!checkOnly && !result.matches) {
    writeFileSync(result.path, result.expected);
    console.log(`Generated ${INDEX_PATH}`);
  } else {
    console.log("Trait effects index is up to date.");
  }
}
