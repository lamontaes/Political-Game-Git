/**
 * Estimates a district in each chamber for every place of the game the
 * Census place-to-district join does not know (places created after the
 * 2020 place list the join was compiled from), and writes
 * src/districts/place-district-estimates.generated.json.
 *
 * For each such place and chamber: the places of its own county (the place
 * map's parent) that the join does know, each weighed by the workers who live
 * there (LODES8 place commuting: live and work there, plus live there and
 * work elsewhere; a place LODES lists no one for counts as one), and the
 * district holding the most of them. A split place's weight is shared among
 * its candidate districts by its Census block population in each where the
 * population file has it, else equally. Ties go to the lower district code.
 * A place whose county has no known place in that chamber gets no estimate.
 *
 *   node --import tsx scripts/districts/estimate-unknown-place-districts.ts [--check]
 *
 * --check exits 1 when the file on disk differs from what this writes.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { recordedPlaceDistrictJoin } from "../../src/districts/place-membership";
import type { DistrictChamber } from "../../src/districts/types";

const ROOT = new URL("../../", import.meta.url);
const read = (path: string) =>
  JSON.parse(readFileSync(fileURLToPath(new URL(path, ROOT)), "utf8"));
const OUT = "src/districts/place-district-estimates.generated.json";
const CHAMBERS: readonly DistrictChamber[] = [
  "congressional",
  "state-upper",
  "state-lower",
];

const map = read("src/core2/data/places/place-map.json") as {
  rows: [string, string, string | null, string, string][];
};
const lodes = read("data/source/lodes-commuting/place-commuting.json") as {
  places: Record<string, [number, number, number]>;
};
const population = read(
  "src/districts/place-district-population.generated.json",
) as { populations: Record<string, Record<string, number>> };

/** The workers who live in a place (LODES), at least one. */
const residents = (geoid: string) => {
  const row = lodes.places[geoid];
  return Math.max(1, row ? row[0] + row[1] : 0);
};

const towns = map.rows.filter((row) => row[1] === "town");
const byCounty = new Map<string, string[]>();
for (const [geoid, , county] of towns)
  if (county) byCounty.set(county, [...(byCounty.get(county) ?? []), geoid]);

const estimates: Record<string, string> = {};
let unknown = 0;
let unplaced = 0;
for (const [geoid, , county] of towns)
  for (const chamber of CHAMBERS) {
    if (recordedPlaceDistrictJoin(geoid, chamber).kind !== "unknown") continue;
    unknown += 1;
    const weights = new Map<string, number>();
    for (const other of byCounty.get(county ?? "") ?? []) {
      if (other === geoid) continue;
      const join = recordedPlaceDistrictJoin(other, chamber);
      const people = residents(other);
      if (join.kind === "whole-place")
        weights.set(
          join.districtGeoid,
          (weights.get(join.districtGeoid) ?? 0) + people,
        );
      else if (join.kind === "split" && join.candidateDistrictGeoids?.length) {
        const split = population.populations[`${other}:${chamber}`];
        const total = split
          ? join.candidateDistrictGeoids.reduce(
              (n, d) => n + (split[d] ?? 0),
              0,
            )
          : 0;
        for (const district of join.candidateDistrictGeoids)
          weights.set(
            district,
            (weights.get(district) ?? 0) +
              (total
                ? (people * (split![district] ?? 0)) / total
                : people / join.candidateDistrictGeoids.length),
          );
      }
    }
    const best = [...weights].sort(
      (a, b) => b[1] - a[1] || a[0].localeCompare(b[0]),
    )[0];
    if (!best) {
      unplaced += 1;
      continue;
    }
    estimates[`${geoid}:${chamber}`] = best[0];
  }

const payload = {
  about:
    "An estimated district, in each chamber, for every place of the game the Census place-to-district join does not know (places created after the 2020 place list it was compiled from): the district holding the most resident workers among the places of the same county the join does know. Generated by scripts/districts/estimate-unknown-place-districts.ts. Stopgap SG-OFFICE-place-district-from-county.",
  sources: [
    "src/core2/data/places/place-map.json (each place's county)",
    "src/districts/place-membership.generated.json (the Census 2020 place-to-district relationship files)",
    "data/source/lodes-commuting/place-commuting.json (LODES8 resident workers by place)",
    "src/districts/place-district-population.generated.json (Census 2020 block population of split places by district)",
  ],
  tag: "ESTIMATED",
  unknownPlaceChambers: unknown,
  withoutEstimate: unplaced,
  estimates: Object.fromEntries(
    Object.entries(estimates).sort((a, b) => a[0].localeCompare(b[0])),
  ),
};
const text = `${JSON.stringify(payload, null, 2)}\n`;
const path = fileURLToPath(new URL(OUT, ROOT));
if (process.argv.includes("--check")) {
  const held = readFileSync(path, "utf8");
  if (held !== text) {
    console.error(`${OUT} is out of date; run this script.`);
    process.exit(1);
  }
  console.log(`${OUT} is current.`);
} else {
  writeFileSync(path, text);
  console.log(
    `${OUT}: ${Object.keys(estimates).length} estimates for ${unknown} unknown place-chambers (${unplaced} with no known place in the county).`,
  );
}
