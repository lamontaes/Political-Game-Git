import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import console from "node:console";
import process from "node:process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const REPOSITORY_ROOT = resolve(dirname(SCRIPT_PATH), "../..");
const MODULE_DIRECTORY = "src/simulation/law-consequences/modules";
const MANIFEST_PATH = "src/simulation/law-consequence-module-manifest.ts";

function assertModuleKey(key) {
  if (!/^[a-z][a-z0-9-]*$/.test(key))
    throw new Error(`Unsupported law consequence module folder name: ${key}`);
}

function registrationBinding(key) {
  assertModuleKey(key);
  return `lawConsequence${key
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("")}Registrations`;
}

export function discoverLawConsequenceModules(root = REPOSITORY_ROOT) {
  const modulesPath = resolve(root, MODULE_DIRECTORY);
  if (!existsSync(modulesPath)) return [];

  const keys = readdirSync(modulesPath, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));

  for (const key of keys) {
    assertModuleKey(key);
    const indexPath = join(modulesPath, key, "index.ts");
    if (!existsSync(indexPath) || !statSync(indexPath).isFile())
      throw new Error(
        `Law consequence module folder must contain index.ts: ${key}`,
      );
    const source = readFileSync(indexPath, "utf8");
    if (
      /(?:from\s*["'][^"']*governing\/public-program(?:\.ts)?["']|import\(["'][^"']*governing\/public-program(?:\.ts)?["']\))/m.test(
        source,
      )
    )
      throw new Error(
        `Law consequence modules must use public-program-capacity-outturn contract types instead of importing the writer: ${key}`,
      );
  }

  return keys;
}

export function renderLawConsequenceManifest(moduleKeys) {
  const keys = [...moduleKeys];
  if (new Set(keys).size !== keys.length)
    throw new Error("Law consequence module keys must be unique.");
  for (const key of keys) assertModuleKey(key);
  if (
    keys.some(
      (key, index) => index > 0 && keys[index - 1].localeCompare(key) > 0,
    )
  )
    throw new Error("Law consequence module keys must be sorted.");

  const imports = keys.map(
    (key) =>
      `import * as ${registrationBinding(key)} from "./law-consequences/modules/${key}";`,
  );
  const moduleKeyRows = keys.map((key) => `  ${JSON.stringify(key)},`);
  const moduleRows = keys.map((key) => `    ${registrationBinding(key)},`);
  const modulesInline = `  [${keys.map(registrationBinding).join(", ")}];`;
  const keysInline = `export const LAW_CONSEQUENCE_MODULE_KEYS = [${keys.map((key) => JSON.stringify(key)).join(", ")}] as const;`;

  return [
    "// Generated by scripts/law-consequence-modules/generate-manifest.mjs. Do not edit by hand.",
    'import type { AnyLawConsequenceKindRegistration } from "./law-consequence-types";',
    'import type { PublicProgramCapacityOutturnReceiverRegistration } from "./public-program-capacity-outturn";',
    ...imports,
    "",
    "interface GeneratedLawConsequenceModule {",
    "  readonly registrations: readonly AnyLawConsequenceKindRegistration[];",
    "  readonly publicProgramCapacityOutturnReceivers?: readonly PublicProgramCapacityOutturnReceiverRegistration[];",
    "}",
    "",
    "const GENERATED_LAW_CONSEQUENCE_MODULES: readonly GeneratedLawConsequenceModule[] =",
    modulesInline.length <= 80
      ? modulesInline
      : `  [\n${moduleRows.join("\n")}\n  ];`,
    "",
    keysInline.length <= 80
      ? keysInline
      : `export const LAW_CONSEQUENCE_MODULE_KEYS = [\n${moduleKeyRows.join("\n")}\n] as const;`,
    "",
    "export const LAW_CONSEQUENCE_MODULE_REGISTRATIONS: readonly AnyLawConsequenceKindRegistration[] =",
    "  Object.freeze(",
    "    GENERATED_LAW_CONSEQUENCE_MODULES.flatMap((module) => module.registrations),",
    "  );",
    "",
    "export const PUBLIC_PROGRAM_CAPACITY_OUTTURN_RECEIVERS: readonly PublicProgramCapacityOutturnReceiverRegistration[] =",
    "  Object.freeze(",
    "    GENERATED_LAW_CONSEQUENCE_MODULES.flatMap(",
    "      (module) => module.publicProgramCapacityOutturnReceivers ?? [],",
    "    ),",
    "  );",
    "",
  ].join("\n");
}

export function checkLawConsequenceManifest(root = REPOSITORY_ROOT) {
  const path = resolve(root, MANIFEST_PATH);
  const expected = renderLawConsequenceManifest(
    discoverLawConsequenceModules(root),
  );
  const actual = existsSync(path) ? readFileSync(path, "utf8") : null;
  return { matches: actual === expected, actual, expected, path };
}

export function writeLawConsequenceManifest(root = REPOSITORY_ROOT) {
  const result = checkLawConsequenceManifest(root);
  if (!result.matches) writeFileSync(result.path, result.expected);
  return result;
}

if (process.argv[1] && resolve(process.argv[1]) === SCRIPT_PATH) {
  const checkOnly = process.argv.includes("--check");
  const result = checkLawConsequenceManifest();
  if (checkOnly && !result.matches) {
    console.error(
      "Law consequence module manifest is out of date. Run npm run generate:law-consequence-modules.",
    );
    process.exitCode = 1;
  } else if (!checkOnly && !result.matches) {
    writeFileSync(result.path, result.expected);
    console.log("Generated src/simulation/law-consequence-module-manifest.ts");
  } else {
    console.log("Law consequence module manifest is up to date.");
  }
}
