export function getNameCorpus(version = DEFAULT_CORPUS_VERSION): NameCorpus {
  const corpus = CORPORA_BY_VERSION[version];
  if (!corpus) {
    throw new Error(
      `Unknown name corpus version: "${version}". Available versions: ${Object.keys(
        CORPORA_BY_VERSION,
      ).join(", ")}`,
    );
  }
  return corpus;
}
