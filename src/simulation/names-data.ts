/**
 * Explicit generation pools, used ONLY as a constraint when a player has
 * stated their character's gender and left the first name blank.
 *
 * WHY THIS EXISTS SEPARATELY. The corpus above carries no demographic
 * attribute, deliberately, and that decision stands: nothing anywhere reads a
 * name and concludes anything about the person holding it. These pools run in
 * exactly one direction: a gender the player stated goes in, a name comes
 * out. A name never flows back the other way.
 *
 * PROVENANCE. The SSA given-name records the corpus is drawn from are
 * published as counts against the sex recorded on the application for a Social
 * Security card. Membership below is this repository's own reading of which
 * pool each corpus name belongs in under those published counts; it is an
 * authored partition, not a field lifted from the source, and it is written
 * out here rather than computed so it can be read and corrected by hand.
 *
 * `neutral` holds the names the published counts do not put decisively on
 * either side. It is the pool a stated non-binary identity draws from, and it
 * is a smaller list than the other two — which is a fact about the starter
 * corpus, not a statement about people.
 *
 * A player who states nothing draws from the whole corpus exactly as before.
 */
export interface GivenNameGenerationPools {
  readonly male: readonly string[];
  readonly female: readonly string[];
  readonly neutral: readonly string[];
}

