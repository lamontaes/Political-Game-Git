const KERNEL_BY_ID = new Map<ExecutiveKernelId, ExecutiveKernelDefinition>(
  EXECUTIVE_GOVERNING_KERNELS.map((kernel) => [kernel.row.id, kernel]),
);

/**
 * The definition for a kernel this wave compiles, or `null`.
 *
 * Null rather than a throw: asking for 92H-K-090 is a reasonable question with
 * a real answer — declaring an emergency needs a mechanic nobody has built —
 * and `executiveGoverningCoverageReport` gives that answer for every row.
 */
export function executiveGoverningKernelById(
  id: ExecutiveKernelId,
): ExecutiveKernelDefinition | null {
  return KERNEL_BY_ID.get(id) ?? null;
}

export type ExecutiveKernelCoverageState =
  "COMPILED_CURRENT_MECHANICS" | "NEEDS_MECHANIC" | "RESEARCH_GAP";

export interface ExecutiveKernelCoverageEntry {
  readonly id: ExecutiveKernelId;
  readonly family: ExecutiveWorkflowFamilyId;
  readonly title: string;
  readonly state: ExecutiveKernelCoverageState;
  /** Present exactly when the state is COMPILED_CURRENT_MECHANICS. */
  readonly definition: ExecutiveKernelDefinition | null;
  readonly blockedBy: readonly string[];
}

/**
 * A developer's ledger of where all seventy 92H kernels stand.
 *
 * Deliberately derived rather than written down: the state comes from the row's
 * own status and from whether a definition exists, so the report cannot drift
 * away from what the compiler will actually accept. It is a view of the
 * research, not a second research authority — nothing here decides a kernel's
 * status, and changing this function cannot promote one.
 */
export function executiveGoverningCoverageReport(): readonly ExecutiveKernelCoverageEntry[] {
  return EXECUTIVE_GOVERNING_KERNEL_ROWS.map((kernelRow) => {
    const definition = executiveGoverningKernelById(kernelRow.id);
    const compiled =
      kernelRow.status === "IMPLEMENTABLE_WITH_CURRENT_MECHANICS" &&
      definition !== null;
    return {
      id: kernelRow.id,
      family: kernelRow.family,
      title: kernelRow.title,
      state: compiled
        ? ("COMPILED_CURRENT_MECHANICS" as const)
        : (kernelRow.status as ExecutiveKernelCoverageState),
      definition: compiled ? definition : null,
      blockedBy: kernelRow.blockedBy,
    };
  });
}
