/**
 * Builds src/core2/data/places/place-lookup.json, the extra facts the core's
 * place lookup (src/core2/place-lookup.ts) needs beyond localities.json,
 * county-names.json, states.json and territory-places.json: state clock
 * defaults, the authored place contexts, the accepted legislative packs'
 * state keys, the county rows, and the seats of government. Tooling only; it
 * reads the old simulation sources once so the core never has to.
 *
 *   npx tsx src/core2/tooling/build-place-lookup-data.ts
 */
import { writeFileSync } from "node:fs";
import {
  ALASKA_CONTEXT,
  KENTUCKY_CONTEXT,
  NEBRASKA_CONTEXT,
} from "../../simulation/legislation-scenarios";
import {
  DEMO_START_DATE,
  LEXINGTON_DEMO_CONTEXT,
} from "../../simulation/demo-jurisdiction-context";
import { LEGISLATIVE_RULE_PACKS } from "../../simulation/legislature-rule-packs";
import { legislativeWorkKey } from "../../simulation/legislative-work-key";
import {
  NATIONAL_COUNTIES_META,
  NATIONAL_COUNTIES_ROWS,
} from "../reference/national-counties.generated";
import { SEATS_OF_GOVERNMENT_ROWS } from "../../simulation/seats-of-government.generated";
import { STATES } from "../../simulation/state-reference";

const clock: Record<
  string,
  { name: string; timeZone: string; utcOffsetMinutes: number }
> = {};
for (const [usps, state] of Object.entries(STATES))
  clock[usps] = {
    name: state.name,
    timeZone: state.timeZone,
    utcOffsetMinutes: state.utcOffsetMinutes,
  };

writeFileSync(
  "src/core2/data/places/place-lookup.json",
  JSON.stringify({
    source:
      "src/simulation state-reference, legislation-scenarios, demo-jurisdiction-context, legislature-rule-packs, national-counties.generated, seats-of-government.generated at port time (generated by src/core2/tooling/build-place-lookup-data.ts)",
    demoStartDate: DEMO_START_DATE,
    states: clock,
    authoredContexts: {
      KENTUCKY_CONTEXT,
      NEBRASKA_CONTEXT,
      ALASKA_CONTEXT,
      LEXINGTON_DEMO_CONTEXT,
    },
    packs: LEGISLATIVE_RULE_PACKS.map((pack) => ({
      jurisdictionKey: pack.jurisdictionKey,
      legislativeScenarioKey: legislativeWorkKey(pack),
      candidacyPackId: `${pack.packId}:candidacy`,
    })),
    counties: {
      source: NATIONAL_COUNTIES_META.source,
      asOf: NATIONAL_COUNTIES_META.asOf,
      columns: ["geoid", "sourceName", "stateUsps"],
      rows: JSON.parse(NATIONAL_COUNTIES_ROWS) as unknown[],
    },
    seats: {
      columns: ["jurisdictionKey", "placeKey", "matchStatus"],
      rows: JSON.parse(SEATS_OF_GOVERNMENT_ROWS) as unknown[],
    },
  }) + "\n",
);
console.log("place-lookup.json written");
