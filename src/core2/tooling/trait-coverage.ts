/**
 * Trait coverage (OPUS-TRAITS, Oct 12, 2026): for every trait in
 * `data/content/trait-act-pulls.json`, the person-decisions in
 * `data/content/trait-decisions.json` that each side of it changes. A side
 * changes a decision when its pulls favor one of the decision's options over
 * another. Tooling only; it reads the data files from disk.
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

export const REPOSITORY_ROOT = resolve(import.meta.dirname, "../../..");

export interface TraitSide {
  toward?: readonly string[];
  away?: readonly string[];
}
export interface TraitRow {
  high?: TraitSide;
  low?: TraitSide;
}
export interface DecisionOption {
  id: string;
  actKinds?: readonly string[];
  from?: string;
}
export interface DecisionRow {
  id: string;
  site: string;
  via?: string;
  owner: string;
  route: "chooser" | "formula";
  options: readonly DecisionOption[];
}
export interface ResolvedDecision extends DecisionRow {
  resolved: readonly { id: string; actKinds: readonly string[] }[];
}
export interface TraitCoverage {
  version: number;
  note: string;
  traits: Record<string, { high: string[]; low: string[] }>;
}

function json<T>(path: string): T {
  return JSON.parse(readFileSync(resolve(REPOSITORY_ROOT, path), "utf8")) as T;
}

export function traitTable(): Record<string, TraitRow> {
  return json<{ pulls: Record<string, TraitRow> }>(
    "data/content/trait-act-pulls.json",
  ).pulls;
}

export function decisionTable(): {
  decisions: DecisionRow[];
  outside: { site: string; why: string }[];
} {
  return json("data/content/trait-decisions.json");
}

/** An option's act kinds, from the table or from the module data row it points at. */
export function resolveOption(option: DecisionOption): {
  id: string;
  actKinds: readonly string[];
} {
  if (option.actKinds) return { id: option.id, actKinds: option.actKinds };
  const [file, pointer] = option.from!.split("#");
  let node: unknown = json(file!);
  for (const part of pointer!.split("/").filter(Boolean))
    node = (node as Record<string, unknown>)[part];
  const row = node as { id?: string; actKinds?: readonly string[] };
  if (row?.id !== option.id || !row.actKinds)
    throw new Error(`${option.from} is not the option ${option.id}.`);
  return { id: option.id, actKinds: row.actKinds };
}

export function resolvedDecisions(): ResolvedDecision[] {
  return decisionTable().decisions.map((row) => ({
    ...row,
    resolved: row.options.map(resolveOption),
  }));
}

/** One side's net pull on each option: toward minus away over its act kinds. */
export function sidePulls(
  side: TraitSide | undefined,
  decision: ResolvedDecision,
): number[] {
  return decision.resolved.map((option) =>
    option.actKinds.reduce(
      (sum, kind) =>
        sum +
        (side?.toward?.includes(kind) ? 1 : 0) -
        (side?.away?.includes(kind) ? 1 : 0),
      0,
    ),
  );
}

export function sideChanges(
  side: TraitSide | undefined,
  decision: ResolvedDecision,
): boolean {
  const pulls = sidePulls(side, decision);
  return pulls.some((value) => value !== pulls[0]);
}

export function buildTraitCoverage(): TraitCoverage {
  const decisions = resolvedDecisions();
  const traits: TraitCoverage["traits"] = {};
  for (const [id, row] of Object.entries(traitTable()).sort(([a], [b]) =>
    a.localeCompare(b),
  ))
    traits[id] = {
      high: decisions.filter((d) => sideChanges(row.high, d)).map((d) => d.id),
      low: decisions.filter((d) => sideChanges(row.low, d)).map((d) => d.id),
    };
  return {
    version: 1,
    note: "Generated by scripts/traits/trait-coverage.ts from trait-act-pulls.json and trait-decisions.json; do not edit by hand. For each trait, the person-decisions its high side and its low side change. src/core2/trait-coverage.test.ts holds the code to it and proves each entry in a generated town.",
    traits,
  };
}
