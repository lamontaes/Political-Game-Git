/**
 * Writes src/core2/data/places/place-map.json: one row for every place the
 * game knows (the country, the 56 jurisdictions, every county area, every
 * town), read from the files that already hold them. Run it after any of
 * those files changes: `npm run place-map`.
 *
 * Row: [id, level, parentId, name, form]. The form is the kind of government
 * the Census listing carries for the place ("municipality", "township",
 * "county"), or "none" where the place has no government of its own (it is
 * then governed by the row above it). Facts a row does not hold are never
 * guessed here: the check reports them.
 */
import { writeFileSync } from "node:fs";
import geography from "../../../data/research/geography/state-reference.json" with { type: "json" };
import { corePlaceByKey, corePlaceStateIdentities } from "../place-lookup";
import { placeLocalities } from "../places";
import { municipiosForPlace } from "../gov-rules/county-governing-body-rules";
import {
  countyGeoidsForPlace,
  countyGovernmentUnit,
  governmentUnitsForPlace,
  municipioUnit,
} from "../reference/government-units";
import { NATIONAL_COUNTIES_ROWS } from "../reference/national-counties.generated";

type Row = [string, string, string | null, string, string];
const rows: Row[] = [["US", "country", null, "United States", "nation"]];

// A state's form is its kind (state, district or territory); "commonwealth"
// is only what its name calls it.
const KIND_FORM: Readonly<Record<string, string>> = {
  state: "state",
  "federal-district": "district",
  territory: "territory",
};
for (const state of corePlaceStateIdentities()) {
  const kind = (
    geography.places as Record<string, { jurisdictionKind: string }>
  )[state.usps]?.jurisdictionKind;
  rows.push([
    state.jurisdictionKey,
    "state",
    "US",
    state.name,
    KIND_FORM[kind ?? ""] ?? "state",
  ]);
}

const countyIds = new Set<string>();
for (const [geoid, name, usps] of JSON.parse(NATIONAL_COUNTIES_ROWS) as [
  string,
  string,
  string,
][]) {
  countyIds.add(geoid);
  const governed = countyGovernmentUnit(geoid) ?? municipioUnit(geoid);
  rows.push([
    `county:${geoid}`,
    "county",
    `US-${usps}`,
    name,
    governed ? "county" : "none",
  ]);
}

for (const state of corePlaceStateIdentities())
  for (const locality of placeLocalities(state.jurisdictionKey)) {
    const geoid = /^\d{7}$/.test(locality.key)
      ? locality.key
      : (corePlaceByKey(locality.key)?.sourceGeoid ?? locality.key);
    // The Census place-in-county files hold no Puerto Rico place; its municipio
    // (a county-level government) comes from the municipal listing.
    const county =
      countyGeoidsForPlace(geoid).find((id) => countyIds.has(id)) ??
      municipiosForPlace(geoid)
        .map((unit) => unit.countyGeoid)
        .find((id): id is string => id !== null && countyIds.has(id)) ??
      // The Census place-in-county files miss a few places; the government
      // listing says which county area the place's own government sits in.
      governmentUnitsForPlace(geoid)
        .map((unit) => unit.countyGeoid)
        .find((id): id is string => id !== null && countyIds.has(id));
    // A municipality that governs the place outranks a township over it.
    const units = governmentUnitsForPlace(geoid);
    const unit =
      units.find((u) => u.unitType === "municipality") ??
      units.find((u) => u.unitType === "township");
    rows.push([
      locality.key,
      "town",
      county ? `county:${county}` : state.jurisdictionKey,
      locality.displayName,
      unit ? unit.unitType : "none",
    ]);
  }

writeFileSync(
  new URL("../data/places/place-map.json", import.meta.url),
  `${JSON.stringify({
    about:
      "The one place map: every place is one row, its level, what it sits under, its name and its form of government. Generated by scripts/maps/build-place-map.ts from the Census place, county and government listings; read only through src/core2/place-map.ts.",
    columns: ["id", "level", "parentId", "name", "form"],
    rows,
  })}\n`,
);
console.log(`place map: ${rows.length} rows`);
