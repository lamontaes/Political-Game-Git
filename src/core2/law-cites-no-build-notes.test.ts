/**
 * A law page shows the statute its research recorded (`terms.cite`, read from
 * an answer's `cite`). That is the real statute or order, or nothing: a build
 * note, a script name or a file path never goes into a field the player reads
 * (player-screen-text). Every `cite` in the starting-law research and in the
 * generated starting law is checked.
 */
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { expect, it } from "vitest";

const DIR = "data/research/laws/starting-law-2026";
const BUILD_NOTE =
  /derived by|generated by|built by|scripts\/|data\/|src\/|\.(json|ts|mjs|py|md)\b/i;

function cites(value: unknown, path: string, out: [string, string][]) {
  if (Array.isArray(value))
    value.forEach((v, i) => cites(v, `${path}[${i}]`, out));
  else if (value && typeof value === "object")
    for (const [key, v] of Object.entries(value)) {
      if (key === "cite" && typeof v === "string")
        out.push([`${path}.cite`, v]);
      else cites(v, `${path}.${key}`, out);
    }
}

it("holds no build note, script name or file path in any cite a player can read", () => {
  const found: [string, string][] = [];
  for (const file of readdirSync(DIR).filter((f) => f.endsWith(".json")))
    cites(JSON.parse(readFileSync(join(DIR, file), "utf8")), file, found);
  cites(
    JSON.parse(readFileSync("src/core2/data/laws/starting-law.json", "utf8")),
    "starting-law.json",
    found,
  );
  expect(found.length, "cites were read").toBeGreaterThan(100);
  const bad = found.filter(([, cite]) => BUILD_NOTE.test(cite));
  expect(bad.map(([where, cite]) => `${where}: ${cite}`)).toEqual([]);
});
