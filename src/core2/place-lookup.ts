/**
 * The core's own place lookup: a place by key or by jurisdiction id, the
 * canonical state identities, a state's own record, a government's seat and
 * the place search. Ported from the old engine's place lookup (the answers
 * were compared before the new game switched over), read from data under
 * `data/places/` and `data/research/`.
 *
 * Sources: the 2025 Census Gazetteer places and counties (identity only), the
 * registered placeholder list of territory villages, the authored hometown
 * rows, and `data/places/place-lookup.json` (state clock defaults, authored
 * contexts, accepted pack keys, county rows, seats), generated by
 * `tooling/build-place-lookup-data.ts`.
 */
import authoredPlaces from "../../data/research/authored-life-places.json" with { type: "json" };
import type { EntityId, IsoDate, SimulationMoment } from "./kernel/brands";
import { makeIsoDate } from "./kernel/dates";
import { createStableId } from "./kernel/ids";
import localityData from "./data/places/localities.json" with { type: "json" };
import lookupData from "./data/places/place-lookup.json" with { type: "json" };
import territoryData from "./data/places/territory-places.json" with { type: "json" };

export interface CorePlaceCapabilities {
  readonly legislativeScenarioKey: string | null;
  readonly candidacyPackId: string | null;
}

export type CorePlaceScope = "state" | "locality" | "county";

export interface CoreJurisdiction {
  readonly id: EntityId;
  readonly slug: string;
  readonly name: string;
  readonly kind: string;
  readonly parentName: string | null;
  readonly provenance: {
    readonly asOf: IsoDate | null;
    readonly source: string | null;
    readonly jurisdiction: EntityId;
    readonly status: "placeholder" | "candidate" | "approved" | "superseded";
  };
}

export interface CorePlaceContext {
  readonly jurisdiction: CoreJurisdiction;
  readonly initialMoment: SimulationMoment;
  readonly creationSummary: string;
  readonly goalScope: string;
  readonly householdLocationLabel: string;
}

export interface CorePlace {
  readonly key: string;
  readonly displayName: string;
  readonly formalName: string | null;
  readonly withinName: string | null;
  readonly context: CorePlaceContext;
  readonly scope: CorePlaceScope;
  readonly stateJurisdictionKey: string | null;
  readonly capabilities: CorePlaceCapabilities;
  readonly sourceGeoid?: string;
}

export interface CorePlaceStateIdentity {
  readonly usps: string;
  readonly jurisdictionKey: string;
  readonly name: string;
}

export type CoreSeatMatchStatus = "known" | "estimated-territory-place";

export interface CoreSeatOfGovernmentPlace {
  readonly jurisdictionKey: string;
  readonly place: CorePlace;
  readonly matchStatus: CoreSeatMatchStatus;
}

type NationwideRow = readonly [
  geoid: string,
  displayName: string,
  stateUsps: string,
];
type TerritoryRow = readonly [
  key: string,
  displayName: string,
  stateUsps: string,
  searchAlias: string | null,
  censusGeoid: string,
  population2020: number,
];
type SeatRow = readonly [
  jurisdictionKey: string,
  placeKey: string,
  matchStatus: CoreSeatMatchStatus,
];

interface StateClock {
  readonly name: string;
  readonly timeZone: string;
  readonly utcOffsetMinutes: number;
}

const STATE_CLOCKS = lookupData.states as Readonly<Record<string, StateClock>>;
const EASTERN: StateClock = {
  name: "",
  timeZone: "America/New_York",
  utcOffsetMinutes: -300,
};
const DEMO_START_DATE = makeIsoDate(lookupData.demoStartDate);
const TERRITORY_SOURCE =
  "Census 2020 Island Areas Demographic and Housing Characteristics files";

const CENSUS_UNIT_TYPES =
  /\s+(?:city|town|village|borough|municipality|metro government|metropolitan government|consolidated government|unified government|urban county government)$/;

function stateName(usps: string): string {
  return STATE_CLOCKS[usps]?.name ?? usps;
}

let countyNamesByUsps: ReadonlyMap<string, ReadonlySet<string>> | null = null;

function countyNamesFor(usps: string): ReadonlySet<string> {
  if (!countyNamesByUsps) {
    const grouped = new Map<string, Set<string>>();
    for (const [, name, code] of countyRows()) {
      const set = grouped.get(code) ?? new Set<string>();
      set.add(name);
      set.add(name.replace(/\s+County$/, ""));
      grouped.set(code, set);
    }
    countyNamesByUsps = grouped;
  }
  return countyNamesByUsps.get(usps) ?? new Set<string>();
}

/** The name a resident uses, derived from the Census label rather than a list. */
export function coreResidentPlaceName(
  censusName: string,
  usps: string,
): string {
  const withoutBalance = censusName.replace(/\s*\(balance\)\s*$/, "");
  const withoutUnit = withoutBalance.replace(CENSUS_UNIT_TYPES, "");
  const merged = /^(.*?)[-/](.+)$/.exec(withoutUnit);
  const head = merged?.[1];
  const suffix = merged?.[2];
  if (head === undefined || suffix === undefined) return withoutUnit;
  const tail = suffix.replace(/\s+County$/, "").trim();
  return countyNamesFor(usps).has(tail) ? head.trim() : withoutUnit;
}

function countyRows(): readonly NationwideRow[] {
  return lookupData.counties.rows as unknown as readonly NationwideRow[];
}

function localityRows(): readonly NationwideRow[] {
  return localityData.rows as unknown as readonly NationwideRow[];
}

function territoryRows(): readonly TerritoryRow[] {
  return territoryData.rows as unknown as readonly TerritoryRow[];
}

/* ------------------------------ authored ---------------------------------- */

let authored: readonly CorePlace[] | null = null;

function allAuthoredPlaces(): readonly CorePlace[] {
  if (authored) return authored;
  const contexts = lookupData.authoredContexts as unknown as Readonly<
    Record<string, CorePlaceContext>
  >;
  const base = authoredPlaces.map(({ contextKey, ...row }) => ({
    ...row,
    context: contexts[contextKey]!,
  })) as unknown as readonly CorePlace[];
  const existingKeys = new Set(base.map((place) => place.stateJurisdictionKey));
  authored = [
    ...base,
    ...lookupData.packs
      .filter((pack) => !existingKeys.has(pack.jurisdictionKey))
      .map((pack): CorePlace => {
        const state = STATE_CLOCKS[pack.jurisdictionKey.slice(3)]!;
        const slug = `state-${pack.jurisdictionKey.toLowerCase()}-placeholder`;
        const id = createStableId("jurisdiction", `definition:${slug}`);
        return {
          key: `state:${pack.jurisdictionKey}`,
          scope: "state",
          stateJurisdictionKey: pack.jurisdictionKey,
          displayName: state.name,
          formalName: null,
          withinName: "United States",
          context: {
            jurisdiction: {
              id,
              slug,
              name: state.name,
              kind: "state-placeholder",
              parentName: "United States",
              provenance: {
                asOf: null,
                source: null,
                jurisdiction: id,
                status: "placeholder",
              },
            },
            initialMoment: {
              date: DEMO_START_DATE,
              minuteOfDay: 550,
              timeZone: state.timeZone,
              utcOffsetMinutes: state.utcOffsetMinutes,
            },
            creationSummary: `Seeded world in ${state.name}.`,
            goalScope: state.name,
            householdLocationLabel: `${state.name} home`,
          },
          capabilities: {
            legislativeScenarioKey: pack.legislativeScenarioKey,
            candidacyPackId: pack.candidacyPackId,
          },
        };
      }),
  ];
  return authored;
}

/* ------------------------------ synthesized ------------------------------- */

function nationwideJurisdictionId(geoid: string): EntityId {
  return createStableId("jurisdiction", `national-place:${geoid}`);
}

function synthesizeNationwidePlace(
  row: NationwideRow,
  scope: "locality" | "county" = "locality",
): CorePlace {
  const [geoid, displayName, usps] = row;
  const state = STATE_CLOCKS[usps];
  const resident = coreResidentPlaceName(displayName, usps);
  const named = `${resident}, ${stateName(usps)}`;
  const county = scope === "county";
  const jurisdictionId = county
    ? createStableId("jurisdiction", `national-county:${geoid}`)
    : nationwideJurisdictionId(geoid);
  const provenance = county ? lookupData.counties : localityData;
  const formal = county
    ? displayName
    : resident === displayName
      ? displayName
      : `${displayName}, ${stateName(usps)}`;
  return {
    key: county ? `county:${geoid}` : geoid,
    displayName: named,
    formalName: formal === named ? null : formal,
    withinName: stateName(usps),
    context: {
      jurisdiction: {
        id: jurisdictionId,
        slug: county ? `us-county-${geoid}` : `us-place-${geoid}`,
        name: named,
        kind: county ? "census-county" : "census-place",
        parentName: stateName(usps),
        provenance: {
          asOf: county ? makeIsoDate(provenance.asOf) : DEMO_START_DATE,
          source: provenance.source,
          jurisdiction: jurisdictionId,
          status: "approved",
        },
      },
      initialMoment: {
        date: DEMO_START_DATE,
        minuteOfDay: 9 * 60 + 10,
        timeZone: state?.timeZone ?? EASTERN.timeZone,
        utcOffsetMinutes: state?.utcOffsetMinutes ?? EASTERN.utcOffsetMinutes,
      },
      creationSummary: county
        ? `Seeded world in ${named}, from the 2025 Census Gazetteer county identity; town unspecified.`
        : `Seeded world in ${named}, from the 2025 Census Gazetteer place identity.`,
      goalScope: named,
      householdLocationLabel: county ? `${named} (town unspecified)` : named,
    },
    scope,
    stateJurisdictionKey: `US-${usps}`,
    capabilities: { legislativeScenarioKey: null, candidacyPackId: null },
    sourceGeoid: geoid,
  };
}

function synthesizeTerritoryPlace(row: TerritoryRow): CorePlace {
  const [key, displayName, usps, , censusGeoid] = row;
  const territory = STATE_CLOCKS[usps];
  const named = `${displayName}, ${stateName(usps)}`;
  const jurisdictionId = createStableId("jurisdiction", key);
  return {
    key,
    displayName: named,
    formalName: null,
    withinName: stateName(usps),
    context: {
      jurisdiction: {
        id: jurisdictionId,
        slug: key.replace(/:/g, "-").toLowerCase(),
        name: named,
        kind: "territory-place",
        parentName: stateName(usps),
        provenance: {
          asOf: null,
          source: TERRITORY_SOURCE,
          jurisdiction: jurisdictionId,
          status: "approved",
        },
      },
      initialMoment: {
        date: DEMO_START_DATE,
        minuteOfDay: 9 * 60 + 10,
        timeZone: territory?.timeZone ?? EASTERN.timeZone,
        utcOffsetMinutes:
          territory?.utcOffsetMinutes ?? EASTERN.utcOffsetMinutes,
      },
      creationSummary: `Seeded world in ${named}, an island-area village from the 2020 Census Island Areas files.`,
      goalScope: named,
      householdLocationLabel: named,
    },
    scope: "locality",
    sourceGeoid: censusGeoid,
    stateJurisdictionKey: `US-${usps}`,
    capabilities: { legislativeScenarioKey: null, candidacyPackId: null },
  };
}

/* -------------------------------- indexes --------------------------------- */

let localityIndex: ReadonlyMap<string, NationwideRow> | null = null;
let geoidByJurisdictionId: ReadonlyMap<EntityId, string> | null = null;
let countyPlaces: ReadonlyMap<string, CorePlace> | null = null;
let countyByJurisdictionId: ReadonlyMap<EntityId, CorePlace> | null = null;
let territoryPlaces: ReadonlyMap<string, CorePlace> | null = null;
let territoryByJurisdictionId: ReadonlyMap<EntityId, CorePlace> | null = null;
let seats: ReadonlyMap<string, SeatRow> | null = null;

function nationwideIndex(): ReadonlyMap<string, NationwideRow> {
  localityIndex ??= new Map(localityRows().map((row) => [row[0], row]));
  return localityIndex;
}

function nationwideGeoids(): ReadonlyMap<EntityId, string> {
  if (!geoidByJurisdictionId) {
    const index = new Map<EntityId, string>();
    for (const [geoid] of localityRows())
      index.set(nationwideJurisdictionId(geoid), geoid);
    geoidByJurisdictionId = index;
  }
  return geoidByJurisdictionId;
}

function nationwideCounties(): ReadonlyMap<string, CorePlace> {
  countyPlaces ??= new Map(
    countyRows().map((row) => {
      const place = synthesizeNationwidePlace(row, "county");
      return [place.key, place];
    }),
  );
  return countyPlaces;
}

function countyForJurisdiction(id: EntityId): CorePlace | null {
  countyByJurisdictionId ??= new Map(
    [...nationwideCounties().values()].map((place) => [
      place.context.jurisdiction.id,
      place,
    ]),
  );
  return countyByJurisdictionId.get(id) ?? null;
}

function territoryIndex(): ReadonlyMap<string, CorePlace> {
  territoryPlaces ??= new Map(
    territoryRows().map((row) => [row[0], synthesizeTerritoryPlace(row)]),
  );
  return territoryPlaces;
}

function territoryForJurisdiction(id: EntityId): CorePlace | null {
  territoryByJurisdictionId ??= new Map(
    [...territoryIndex().values()].map((place) => [
      place.context.jurisdiction.id,
      place,
    ]),
  );
  return territoryByJurisdictionId.get(id) ?? null;
}

/* --------------------------------- lookups -------------------------------- */

export function corePlaceByKey(key: string): CorePlace | null {
  const known = allAuthoredPlaces().find((place) => place.key === key);
  if (known) return known;
  if (key.startsWith("county:")) return nationwideCounties().get(key) ?? null;
  if (key.startsWith("territory:")) return territoryIndex().get(key) ?? null;
  const row = nationwideIndex().get(key);
  return row ? synthesizeNationwidePlace(row) : null;
}

export function corePlaceByJurisdictionId(
  jurisdictionId: EntityId,
): CorePlace | null {
  const known = allAuthoredPlaces().find(
    (place) => place.context.jurisdiction.id === jurisdictionId,
  );
  if (known) return known;
  const county = countyForJurisdiction(jurisdictionId);
  if (county) return county;
  const territory = territoryForJurisdiction(jurisdictionId);
  if (territory) return territory;
  const geoid = nationwideGeoids().get(jurisdictionId);
  if (geoid === undefined) return null;
  const row = nationwideIndex().get(geoid);
  return row ? synthesizeNationwidePlace(row) : null;
}

/** A state's or territory's name by its USPS code (`KY`); null when unknown. */
export function coreStateName(usps: string): string | null {
  return STATE_CLOCKS[usps]?.name ?? null;
}

/** Canonical USPS / `US-KY` identities, not names recovered from place labels. */
export function corePlaceStateIdentities(): readonly CorePlaceStateIdentity[] {
  return Object.entries(STATE_CLOCKS)
    .map(([usps, state]) => ({
      usps,
      jurisdictionKey: `US-${usps}`,
      name: state.name,
    }))
    .sort((left, right) => left.name.localeCompare(right.name));
}

/** Resolve a government's seat through the same lookup as an ordinary town. */
export function coreSeatOfGovernmentPlace(
  jurisdictionKey: string,
): CoreSeatOfGovernmentPlace | null {
  seats ??= new Map(
    (lookupData.seats.rows as unknown as readonly SeatRow[]).map((row) => [
      row[0],
      row,
    ]),
  );
  const row = seats.get(jurisdictionKey);
  if (!row) return null;
  const place = corePlaceByKey(row[1]);
  if (!place) return null;
  if (
    jurisdictionKey !== "US-FEDERAL" &&
    place.stateJurisdictionKey !== jurisdictionKey
  )
    return null;
  return { jurisdictionKey: row[0], place, matchStatus: row[2] };
}

/**
 * A state's jurisdiction by its key (`US-KY`): the authored or rule-pack
 * state place's own record, else a placeholder record with the state's name,
 * never a playable place and never a borrowed capability.
 */
export function coreStateJurisdiction(key: string): CoreJurisdiction | null {
  if (!stateJurisdictions.has(key))
    stateJurisdictions.set(key, findStateJurisdiction(key));
  return stateJurisdictions.get(key)!;
}

const stateJurisdictions = new Map<string, CoreJurisdiction | null>();

function findStateJurisdiction(key: string): CoreJurisdiction | null {
  const established = allAuthoredPlaces().find(
    (place) => place.scope === "state" && place.stateJurisdictionKey === key,
  );
  if (established) return established.context.jurisdiction;
  const state = /^US-[A-Z]{2}$/.test(key) ? STATE_CLOCKS[key.slice(3)] : null;
  if (!state) return null;
  const slug = `state-${key.toLowerCase()}-placeholder`;
  const id = createStableId("jurisdiction", `definition:${slug}`);
  return {
    id,
    slug,
    name: state.name,
    kind: "state-placeholder",
    parentName: "United States",
    provenance: {
      asOf: null,
      source: null,
      jurisdiction: id,
      status: "placeholder",
    },
  };
}

/* --------------------------------- search --------------------------------- */

export interface CorePlaceSearchOptions {
  /** Only places in this state (`US-AL`), matched by identity, not by name. */
  readonly stateJurisdictionKey?: string;
  /** Only this scope; a locality search leaves out statewide rows. */
  readonly scope?: CorePlaceScope;
}

let rowsByUsps: ReadonlyMap<string, readonly NationwideRow[]> | null = null;
let authoredGeoids: ReadonlySet<string> | null = null;

function localityRowsByUsps(): ReadonlyMap<string, readonly NationwideRow[]> {
  if (!rowsByUsps) {
    const grouped = new Map<string, NationwideRow[]>();
    for (const row of localityRows()) {
      const list = grouped.get(row[2]);
      if (list) list.push(row);
      else grouped.set(row[2], [row]);
    }
    rowsByUsps = grouped;
  }
  return rowsByUsps;
}

function authoredSourceGeoids(): ReadonlySet<string> {
  authoredGeoids ??= new Set(
    allAuthoredPlaces()
      .map((place) => place.sourceGeoid)
      .filter((geoid): geoid is string => geoid !== undefined),
  );
  return authoredGeoids;
}

function placeMatches(place: CorePlace, needle: string): boolean {
  return [place.displayName, place.withinName ?? "", place.formalName ?? ""]
    .join(" ")
    .toLowerCase()
    .includes(needle);
}

function labelMatches(label: string, needle: string): boolean {
  return needle.length === 0 || label.toLowerCase().includes(needle);
}

function authoredMatches(
  place: CorePlace,
  needle: string,
  stateKey: string | undefined,
): boolean {
  if (stateKey && place.stateJurisdictionKey !== stateKey) return false;
  if (!stateKey) return placeMatches(place, needle);
  const localName = place.withinName
    ? place.displayName.replace(
        new RegExp(`,\\s*${place.withinName}$`, "i"),
        "",
      )
    : place.displayName;
  return (
    labelMatches(localName, needle) ||
    labelMatches(place.formalName ?? "", needle)
  );
}

function territoryMatches(
  row: TerritoryRow,
  needle: string,
  inTerritory: boolean,
): boolean {
  const local = `${row[1]} ${row[3] ?? ""}`;
  const haystack = inTerritory
    ? local
    : `${local} ${stateName(row[2])} ${row[2]}`;
  return haystack.toLowerCase().includes(needle);
}

/** Whether a place is the one whose name was typed, not one containing it. */
function namesExactly(place: CorePlace, needle: string): boolean {
  if (needle.length === 0) return false;
  const name = place.displayName.toLowerCase();
  return (
    name === needle ||
    name.startsWith(`${needle},`) ||
    (place.formalName ?? "").toLowerCase() === needle
  );
}

/** The place actually named first, then everything else by name, then key. */
function searchOrder(left: CorePlace, right: CorePlace, needle: string) {
  const leftExact = namesExactly(left, needle);
  const rightExact = namesExactly(right, needle);
  if (leftExact !== rightExact) return leftExact ? -1 : 1;
  const byName = left.displayName.localeCompare(right.displayName, "en", {
    sensitivity: "base",
  });
  if (byName !== 0) return byName;
  return left.key.localeCompare(right.key, "en");
}

/**
 * Places matching a typed search, authored rows, Census places, territory
 * villages and counties together, filtered and ordered before `limit` is
 * applied. An empty query with a state lists that state's places.
 */
export function searchCorePlaces(
  query: string,
  limit = 20,
  options?: CorePlaceSearchOptions,
): readonly CorePlace[] {
  const needle = query.trim().toLowerCase();
  const stateKey = options?.stateJurisdictionKey;
  const usps = stateKey
    ? (/^US-([A-Z]{2})$/.exec(stateKey)?.[1] ?? null)
    : null;
  if (stateKey && !usps) return [];
  if (!stateKey && needle.length === 0) return [];

  const skip = authoredSourceGeoids();
  const seen = new Set<string>();
  const matches: CorePlace[] = [];
  const take = (place: CorePlace) => {
    if (options?.scope && place.scope !== options.scope) return;
    if (stateKey && place.stateJurisdictionKey !== stateKey) return;
    if (seen.has(place.key)) return;
    seen.add(place.key);
    matches.push(place);
  };

  for (const place of allAuthoredPlaces())
    if (authoredMatches(place, needle, stateKey)) take(place);
  if (options?.scope !== "state") {
    const rows = usps ? (localityRowsByUsps().get(usps) ?? []) : localityRows();
    for (const row of rows) {
      if (skip.has(row[0])) continue;
      if (usps) {
        if (!labelMatches(row[1], needle)) continue;
      } else {
        const haystack =
          `${row[1]} ${stateName(row[2])} ${row[2]}`.toLowerCase();
        if (!haystack.includes(needle)) continue;
      }
      take(synthesizeNationwidePlace(row));
    }
    for (const row of territoryRows()) {
      if (usps && row[2] !== usps) continue;
      if (!territoryMatches(row, needle, usps !== null)) continue;
      take(territoryIndex().get(row[0])!);
    }
    for (const place of nationwideCounties().values())
      if (placeMatches(place, needle)) take(place);
  }

  if (limit === 1) {
    let first: CorePlace | undefined;
    for (const place of matches)
      if (!first || searchOrder(place, first, needle) < 0) first = place;
    return first ? [first] : [];
  }
  matches.sort((left, right) => searchOrder(left, right, needle));
  return matches.slice(0, limit);
}
